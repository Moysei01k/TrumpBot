"""python -m trumpbot [play|roster|export] [--speed N] [--seed N]"""
import argparse
import json
import sys
import time
from pathlib import Path

from .core import simulate
from .west_wing import ROOMS

COLORS = {"reader": 36, "checker": 32, "router": 35, "scribe": 33, "director": 34, "potus": 31}


def paint(text: str, code: int) -> str:
    return f"\033[{code}m{text}\033[0m" if sys.stdout.isatty() else text


def play(run, speed: float) -> None:
    roles = {a.key: a.role for a in run.agents} | {"director": "director", "potus": "potus"}
    print(paint("GROK WHITE HOUSE", 1), " TrumpBot · 04 rooms / 12 agents · fictional satire")
    clock, room = 0.0, None
    for e in run.events:
        if speed > 0:
            time.sleep(max(0.0, (e.t - clock) / speed))
        clock = e.t
        if e.room != room:
            room = e.room
            name = next(r.name for r in ROOMS if r.key == room)
            print(paint(f"\n── NOW / {name.upper()} " + "─" * (40 - len(name)), 1))
        tag = paint(f"{e.agent.upper():<9}", COLORS[roles[e.agent]])
        text = f'"{e.text}"' if e.agent == "potus" else e.text
        print(f"  {int(e.t):02d}s  {tag} {text}")
    s = run.summary()
    print(f"\nTASKS {s['tasks']}  DONE {s['done']}  HELD {s['held']}  "
          f"DUPLICATES CAUGHT {s['duplicates']}  SOURCE LINKS {s['source_links']}  CUTS {s['cuts']}")


def roster(run) -> None:
    print(f"{'#':<4}{'AGENT':<10}{'ROLE':<9}{'DEPARTMENT':<14}{'HOME':<9}TASKS")
    for i, a in enumerate(run.agents, 1):
        jobs = ", ".join(f"#{tid:02d}" if tid > 0 else "dupe" for _, _, tid in a.shifts) or "-"
        print(f"{i:02d}  {a.key.upper():<10}{a.role:<9}{a.department:<14}{a.home:<9}{jobs}")


def export(run, path: Path) -> None:
    payload = json.dumps(run.to_dict(), indent=1)
    path.write_text(f"// generated by `python -m trumpbot export`, do not edit\nwindow.TIMELINE = {payload};\n")
    print(f"wrote {path} ({len(run.events)} events, {len(run.tasks)} tasks)")


def main() -> None:
    p = argparse.ArgumentParser(prog="trumpbot", description="One president. Twelve agents. Fictional satire.")
    p.add_argument("command", nargs="?", default="play", choices=["play", "roster", "export"])
    p.add_argument("path", nargs="?", default="web/timeline.js")
    p.add_argument("--speed", type=float, default=4.0, help="playback speed, 0 = instant (default 4x)")
    p.add_argument("--seed", type=int, default=47)
    args = p.parse_args()

    run = simulate(args.seed)
    if args.command == "play":
        play(run, args.speed)
    elif args.command == "roster":
        roster(run)
    else:
        export(run, Path(args.path))


if __name__ == "__main__":
    main()
